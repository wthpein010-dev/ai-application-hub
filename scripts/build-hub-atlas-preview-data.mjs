import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadDefaultAppsFromRuntime } from "../tests/helpers/default-apps.mjs";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const runtimePath = join(root, "app-20260706-restore-games.js");
const outputPath = join(
  root,
  "design-previews",
  "hub-interactive-atlas",
  "data.generated.js",
);

const PALETTES = [
  { accent: "#0e7a68", surface: "#dff5ee", ink: "#093f37" },
  { accent: "#dc6a2e", surface: "#fff0e7", ink: "#6f2b0d" },
  { accent: "#2868c7", surface: "#e7f0ff", ink: "#173f7b" },
  { accent: "#9d4a78", surface: "#faeaf3", ink: "#642645" },
  { accent: "#687125", surface: "#f1f3d8", ink: "#414817" },
  { accent: "#7160bf", surface: "#efecff", ink: "#40347e" },
];

const ACTION_LABELS = {
  web: "网页预览",
  video: "介绍视频",
  windows: "Wins下载",
  mac: "Mac下载",
  ios: "iOS安装",
};

function hashId(id) {
  return Array.from(id).reduce(
    (hash, character) => ((hash * 31) + character.codePointAt(0)) >>> 0,
    7,
  );
}

function normalizeTarget(value, fallbackLabel) {
  if (!value) return null;
  if (typeof value === "string") {
    return value.trim() ? { href: value.trim(), sourceLabel: fallbackLabel } : null;
  }
  if (typeof value === "object" && typeof value.href === "string") {
    const href = value.href.trim();
    return href ? { href, sourceLabel: value.label || fallbackLabel } : null;
  }
  return null;
}

function makeAction(type, value) {
  const target = normalizeTarget(value, ACTION_LABELS[type]);
  return target
    ? {
        type,
        label: ACTION_LABELS[type],
        href: target.href,
        sourceLabel: target.sourceLabel,
      }
    : null;
}

function projectKind(app) {
  if (app.status === "game") return "game";
  if (app.status === "ai" || app.status === "engineering") {
    return "engineering";
  }
  return "app";
}

function projectMark(name) {
  const compact = Array.from(String(name || "AI").replace(/\s+/gu, ""));
  return compact.slice(0, 2).join("").toUpperCase();
}

export function buildPreviewProjects(apps) {
  return apps.map((app, index) => {
    const platforms = app.platforms || {};
    const actions = [
      makeAction("web", platforms.web || app.entry),
      makeAction("video", app.video),
      makeAction("windows", platforms.windows || app.package),
      makeAction("mac", platforms.mac),
      makeAction("ios", platforms.ios),
    ].filter(Boolean);
    const uniqueActions = actions.filter(
      (action, actionIndex) =>
        actions.findIndex(
          (candidate) =>
            candidate.type === action.type && candidate.href === action.href,
        ) === actionIndex,
    );
    const palette = PALETTES[hashId(app.id) % PALETTES.length];

    return {
      id: app.id,
      index,
      name: app.name,
      category: app.category || "未分类",
      kind: projectKind(app),
      badge: app.badge || "",
      brief: app.brief || "",
      problem: app.problem || "",
      aiUse: app.aiUse || "",
      tags: Array.isArray(app.tags) ? app.tags : [],
      actions: uniqueActions,
      visual: {
        ...palette,
        mark: projectMark(app.name),
      },
    };
  });
}

export function writePreviewData(projects, path = outputPath) {
  mkdirSync(dirname(path), { recursive: true });
  const contents = [
    "// Generated by scripts/build-hub-atlas-preview-data.mjs.",
    "// Do not edit this file by hand.",
    `export const projects = ${JSON.stringify(projects, null, 2)};`,
    "",
  ].join("\n");
  writeFileSync(path, contents, "utf8");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const runtime = readFileSync(runtimePath, "utf8");
  const projects = buildPreviewProjects(loadDefaultAppsFromRuntime(runtime));
  writePreviewData(projects);
  process.stdout.write(`Generated ${projects.length} preview projects.\n`);
}
